export function Sidebar() {
  const pathname = usePathname();

  const isActive = (href: string) => {
    if (href === "/dashboard") return pathname === "/dashboard";
    if (href === "/reports") return pathname === "/reports";
    if (href === "/settings") return pathname === "/settings";
    return pathname === href || pathname.startsWith(href + "/");
  };

  return (
    <aside className="fixed left-0 top-0 z-40 flex h-screen w-64 flex-col border-r border-[var(--border)] bg-[var(--surface)]">
      <div className="flex h-16 shrink-0 items-center gap-3 border-b border-[var(--border)] px-5">
        <div className="relative h-9 w-9 overflow-hidden rounded-md">
          <Image
            src="/wpt-logo.jpg"
            alt="WPT Accounts"
            fill
            className="object-cover"
            priority
          />
        </div>
        <div className="flex flex-col">
          <span className="text-sm font-bold tracking-tight">WPT Accounts</span>
          <span className="text-[10px] text-[var(--text-muted)]">Web Power Tech</span>
        </div>
      </div>

      <nav className="flex-1 overflow-y-auto p-3">
        {sections.map((section) => (
          <div key={section.title} className="mb-4">
            <div className="mb-1.5 px-3 text-[10px] font-semibold uppercase tracking-wider text-[var(--text-muted)]">
              {section.title}
            </div>
            <div className="space-y-0.5">
              {section.items.map((item) => {
                const active = isActive(item.href);
                return (
                  <Link
                    key={item.href}
                    href={item.href}
                    className={`flex items-center gap-2.5 rounded-lg px-3 py-2 text-sm font-medium transition-colors ${
                      active
                        ? "bg-[var(--primary)] text-white"
                        : "text-[var(--text-secondary)] hover:bg-[var(--surface-elevated)] hover:text-[var(--text-primary)]"
                    }`}
                  >
                    <span className={active ? "text-white" : "text-[var(--text-muted)]"}>
                      {item.icon}
                    </span>
                    <span className="truncate">{item.label}</span>
                  </Link>
                );
              })}
            </div>
          </div>
        ))}
      </nav>

      <div className="shrink-0 border-t border-[var(--border)] p-4">
        <div className="rounded-lg bg-[var(--background)] px-3 py-2 text-xs text-[var(--text-muted)]">
          Role:{" "}
          <span className="font-medium text-[var(--text-secondary)]">Accountant</span>
        </div>
      </div>
    </aside>
  );
}
